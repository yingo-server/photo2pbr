# ═══════════════════════════════════════════════════════════════════
# Radiance .hdr（RGBE + RLE）
# ═══════════════════════════════════════════════════════════════════
def _pack_scanline(chan: np.ndarray) -> bytes:
    """Radiance RLE 约定：code>128 → 重复(code-128)次；否则 → 字面量 code 个字节。"""
    out = bytearray()
    n = len(chan)
    i = 0
    while i < n:
        j = i
        while j + 1 < n and chan[j + 1] == chan[i]:
            j += 1
        run = j - i + 1
        if run >= 4:
            while run > 0:
                r = min(run, 127)
                out.append(128 + r)
                out.append(int(chan[i]))
                run -= r
            i = j + 1
            continue
        k = i
        while k < n and (k - i) < 128:
            if k + 3 < n and chan[k] == chan[k + 1] == chan[k + 2] == chan[k + 3]:
                break
            k += 1
        out.append(k - i)
        out.extend(int(v) for v in chan[i:k])
        i = k
    return bytes(out)


def write_hdr(path: str | Path, rgb: np.ndarray) -> str:
    """线性 RGB float → Radiance .hdr（RGBE + 扫描线 RLE）。"""
    rgb = np.clip(np.asarray(rgb, dtype=np.float64), 0.0, None)
    h, w, _ = rgb.shape
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "wb") as f:
        f.write(b"#?RADIANCE\nFORMAT=32-bit_rle_rgbe\n\n")
        f.write(("-Y %d +X %d\n" % (h, w)).encode("ascii"))
        for row in rgb.reshape(-1, w, 3) if rgb.ndim == 3 else rgb:
            mx = row.max(axis=1)
            nz = mx > 1e-32
            rgbe = np.zeros((w, 4), np.uint8)
            if nz.any():
                m, e = np.frexp(mx[nz])
                scale = m * 256.0 / mx[nz]
                for c in range(3):
                    rgbe[nz, c] = np.clip(row[nz, c] * scale, 0, 255).astype(np.uint8)
                rgbe[nz, 3] = np.clip(e + 128, 0, 255).astype(np.uint8)
            f.write(bytes([2, 2, (w >> 8) & 0xFF, w & 0xFF]))
            for c in range(4):
                f.write(_pack_scanline(rgbe[:, c]))
    return str(path)


